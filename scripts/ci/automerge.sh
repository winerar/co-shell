#!/usr/bin/env bash
# Auto-merge of agent PRs into dev (.github/workflows/automerge.yml). Needs GH_TOKEN and GH_REPO.
#   scripts/ci/automerge.sh <pr-number | head-branch>
# Merges only when: base dev, head claude/* or ccr-*, not a draft, no `hold` label, the latest CI run
# on the head commit succeeded. After the merge CI is dispatched on dev (a GITHUB_TOKEN merge does
# not trigger push workflows). A conflicting PR gets one comment with the fix.
set -euo pipefail
target=${1:?pr number or head branch}

info=$(gh pr view "$target" --json number,state,isDraft,baseRefName,headRefName,headRefOid,labels,mergeable 2>/dev/null) ||
    { echo "No PR for $target"; exit 0; }
field() { jq -r "$1" <<<"$info"; }
num=$(field .number) sha=$(field .headRefOid) head=$(field .headRefName)

skip() { echo "PR #$num: skip — $*"; exit 0; }
[ "$(field .state)" = OPEN ] || skip "not open"
[ "$(field .baseRefName)" = dev ] || skip "base is not dev"
case "$head" in claude/* | ccr-*) ;; *) skip "branch $head is not an agent branch" ;; esac
[ "$(field .isDraft)" = false ] || skip "draft (agent marks it ready at the end of the session)"
field '.labels[].name' | grep -qx hold && skip "label hold"

run=$(gh run list --workflow ci.yml --commit "$sha" --limit 1 --json status,conclusion -q '.[0] | "\(.status) \(.conclusion)"')
[ "$run" = "completed success" ] || skip "CI on ${sha:0:7}: ${run:-no run}"

# GitHub computes mergeability lazily: UNKNOWN right after a push.
for _ in 1 2 3 4 5 6; do
    mergeable=$(gh pr view "$num" --json mergeable -q .mergeable)
    [ "$mergeable" != UNKNOWN ] && break
    sleep 5
done
if [ "$mergeable" = CONFLICTING ]; then
    marker='<!-- automerge -->'
    gh pr view "$num" --json comments -q '.comments[].body' | grep -qF "$marker" ||
        gh pr comment "$num" --body "$marker
Конфликт с \`dev\` — автомерж ждёт. Агенту: \`scripts/agent/sync-dev.sh\`, разрешить, push.

---
_Generated by [Claude Code](https://claude.ai/code)_"
    skip "conflicts with dev"
fi
[ "$mergeable" = MERGEABLE ] || skip "mergeable=$mergeable"

gh pr merge "$num" --merge --delete-branch --match-head-commit "$sha"
echo "PR #$num merged into dev"
gh workflow run ci.yml --ref dev
