#!/usr/bin/env python3
"""Moves task statuses by PR events, so the board does not wait for a person (automerge.sh, docs/agents/tasks.md).

  task_status.py ready  <pr>             PR is ready (not a draft): the open issues it names → `status:in-progress`
                                          (only from next / backlog / triage: a question to the owner stays where it is)
  task_status.py merged <pr> [fixed…]    PR merged: the issues it names but does not fix, still in progress and named
                                          by no other ready open PR → back to `status:next` with a comment

An issue is «named» by `#N` anywhere in the PR title or body (agents write «Add X (#584)», «Related: #584»);
`Fixes #N` issues are closed by automerge.sh itself. Prints `changed` when a label moved — the caller then
dispatches tasks.yml (a GITHUB_TOKEN label change does not trigger workflows). Needs GH_TOKEN and GH_REPO.
"""
import json
import os
import re
import subprocess
import sys

MENTION = re.compile(r"(?<![\w/&])#(\d+)\b")
STATUS = "status:"
IN_PROGRESS = "status:in-progress"
NEXT = "status:next"
TAKE_FROM = {"status:next", "status:backlog", "status:triage", None}
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def mentions(text):
    """Issue numbers named as `#N` in the text, in order, without duplicates."""
    seen = []
    for n in MENTION.findall(text or ""):
        if int(n) not in seen:
            seen.append(int(n))
    return seen


def status_of(labels):
    return next((l for l in labels if l.startswith(STATUS)), None)


def plan_ready(issues):
    """issues: [{number, state, labels, is_pr}] → [(number, old status, new status)]."""
    return [
        (i["number"], status_of(i["labels"]), IN_PROGRESS)
        for i in issues
        if not i["is_pr"] and i["state"] == "OPEN" and status_of(i["labels"]) in TAKE_FROM
    ]


def plan_merged(issues, fixed, named_elsewhere):
    """Named but not fixed, still in progress, no other ready PR names it → back to «Очередь»."""
    return [
        (i["number"], IN_PROGRESS, NEXT)
        for i in issues
        if not i["is_pr"] and i["state"] == "OPEN" and i["number"] not in fixed
        and status_of(i["labels"]) == IN_PROGRESS and i["number"] not in named_elsewhere
    ]


def gh(*args):
    return subprocess.run(["gh", *args], check=True, capture_output=True, text=True).stdout


def repo():
    return os.environ["GH_REPO"]


def pr_text(num):
    pr = json.loads(gh("api", f"repos/{repo()}/pulls/{num}"))
    return f"{pr.get('title') or ''}\n{pr.get('body') or ''}"


def load_issue(n):
    try:
        i = json.loads(gh("api", f"repos/{repo()}/issues/{n}"))
    except subprocess.CalledProcessError:
        return None  # `#N` of another repo, a deleted issue
    return {"number": n, "state": i["state"].upper(), "labels": [l["name"] for l in i["labels"]],
            "is_pr": "pull_request" in i}


def named_by_other_prs(num):
    prs = json.loads(gh("api", f"repos/{repo()}/pulls?state=open&base=dev&per_page=100"))
    named = set()
    for p in prs:
        if p["number"] != num and not p.get("draft"):
            named.update(mentions(f"{p.get('title') or ''}\n{p.get('body') or ''}"))
    return named


def apply(moves, comment=None):
    for n, old, new in moves:
        args = ["issue", "edit", str(n), "--add-label", new]
        if old:
            args += ["--remove-label", old]
        gh(*args)
        if comment:
            gh("issue", "comment", str(n), "--body", comment + FOOTER)
        print(f"Issue #{n}: {old or 'no status'} → {new}")
    if moves:
        print("changed")


def main(argv):
    if len(argv) < 2 or argv[0] not in ("ready", "merged"):
        sys.exit(__doc__)
    num = int(argv[1])
    issues = [i for i in map(load_issue, mentions(pr_text(num))) if i]
    if argv[0] == "ready":
        apply(plan_ready(issues))
    else:
        fixed = {int(n) for n in argv[2:]}
        apply(plan_merged(issues, fixed, named_by_other_prs(num)),
              f"Часть влита в #{num}, задача не закрыта (в PR нет «Fixes #N») — вернул в «Очередь». "
              "Что осталось — в описании PR. Готово целиком — закройте или следующий PR с «Fixes».")


if __name__ == "__main__":
    main(sys.argv[1:])
