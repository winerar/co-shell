package app.coshell.release

import app.coshell.newmark.NewFeatures
import java.io.File
import org.junit.Assert.assertTrue
import org.junit.Test

/** The release-stories rule (#693): at most five, a key of their own, schemes made by the script. */
class ReleaseStoriesTest {
    @Test
    fun `a release has one to five stories`() {
        assertTrue(ReleaseStories.current.size in 1..ReleaseStories.MAX)
    }

    @Test
    fun `stories are different`() {
        assertTrue(ReleaseStories.current.map { it.title }.toSet().size == ReleaseStories.current.size)
    }

    @Test
    fun `the set has its own new-mark key`() {
        assertTrue(ReleaseStories.KEY in NewFeatures.tracked)
        assertTrue(ReleaseStories.KEY !in NewFeatures.all)
    }

    @Test
    fun `scheme layers are generated by the script`() {
        val drawables = listOf(File("src/main/res/drawable"), File("app/src/main/res/drawable")).first { it.isDirectory }
        val layers = drawables.listFiles().orEmpty().filter { it.name.startsWith("story_") }
        assertTrue(layers.isNotEmpty())
        layers.forEach { assertTrue(it.name, "story_art_693.py" in it.readText()) }
    }
}
