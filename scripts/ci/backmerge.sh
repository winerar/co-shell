#!/usr/bin/env bash
# After a hotfix (docs/agents/hotfix.md): bring main into dev, so the fix is not lost and the next release
# dev → main does not conflict. Called by automerge.sh right after the hotfix PR is merged into main.
#   scripts/ci/backmerge.sh <hotfix-pr-number>      (needs GH_TOKEN, GH_REPO and a full clone)
# Merges origin/main into a branch off origin/dev, opens a PR into dev and merges it at once (the fix was
# checked in its PR; CI on dev, dispatched here, checks the combined tree). whats-new.md merges by `union`
# (.gitattributes): dev's unreleased section stays on top. Any other conflict → one comment on the hotfix
# PR, nothing is merged.
set -euo pipefail
pr=${1:?hotfix pr number}

git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
git fetch -q origin main dev
if git merge-base --is-ancestor origin/main origin/dev; then echo "dev already contains main"; exit 0; fi

branch="backmerge/hotfix-$pr"
git checkout -q -B "$branch" origin/dev
if ! git merge -q --no-ff --no-edit -m "Merge main into dev after hotfix #$pr" origin/main; then
    conflicts=$(git diff --name-only --diff-filter=U | sed 's/^/- `/; s/$/`/')
    git merge --abort
    gh pr comment "$pr" --body "<!-- backmerge -->
Хотфикс выпущен, но \`main\` не влился в \`dev\` сам — конфликт:
$conflicts

Агенту: ветка от \`origin/dev\`, \`git merge origin/main\`, разрешить, PR в \`dev\`.

---
_Generated by [Claude Code](https://claude.ai/code)_"
    echo "✗ conflicts merging main into dev"; exit 1
fi
git push -q origin "$branch"
gh pr create --base dev --head "$branch" --title "Merge main into dev after hotfix #$pr" \
    --body "Хотфикс #$pr уже на телефонах; это слияние возвращает его в \`dev\` (\`scripts/ci/backmerge.sh\`)."
gh pr merge "$branch" --merge --delete-branch
gh workflow run ci.yml --ref dev
echo "main merged into dev"
