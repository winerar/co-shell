#!/usr/bin/env bash
# Auto-merge of agent PRs into dev (.github/workflows/automerge.yml). Needs GH_TOKEN and GH_REPO.
#   scripts/ci/automerge.sh <pr-number | head-branch>
# Merges only when: base dev, head claude/*, ccr-* or hotfix/*, not a draft, no `hold` label, a CI run on the head
# commit succeeded. After the merge CI is dispatched on dev (a GITHUB_TOKEN merge does
# not trigger push workflows). A conflicting PR gets one comment with the fix.
# Hotfix (docs/agents/hotfix.md): base main — merged only from the `hotfix` job of ci.yml, after CI and the
# emulator are green (HOTFIX_GREEN_SHA = head commit); then CI on main publishes the build and
# backmerge.sh brings main into dev.
# A GITHUB_TOKEN merge also does not close the issues named by `Fixes #N`, and an issue closed with
# GITHUB_TOKEN does not trigger tasks.yml — so the script closes them, drops their `status:*` labels
# and dispatches the board sync itself.
set -euo pipefail
target=${1:?pr number or head branch}

info=$(gh pr view "$target" --json number,state,isDraft,baseRefName,headRefName,headRefOid,labels,mergeable 2>/dev/null) ||
    { echo "No PR for $target"; exit 0; }
field() { jq -r "$1" <<<"$info"; }
num=$(field .number) sha=$(field .headRefOid) head=$(field .headRefName)

skip() { echo "PR #$num: skip — $*"; exit 0; }
[ "$(field .state)" = OPEN ] || skip "not open"
base=$(field .baseRefName)
case "$base" in dev | main) ;; *) skip "base is $base" ;; esac
case "$head" in claude/* | ccr-* | hotfix/*) ;; *) skip "branch $head is not an agent branch" ;; esac
[ "$(field .isDraft)" = false ] || skip "draft (agent marks it ready at the end of the session)"
field '.labels[].name' | grep -qx hold && skip "label hold"

# Any green run of the head commit counts: a commit often has a dispatched run and a pull_request run,
# and the newest may be an empty or cancelled duplicate (runs 320/321) that would hide the green one.
# CI_GREEN_SHA — set by the last step of a green CI run (ci.yml), which is still in progress here.
if [ "$base" = main ]; then
    [ "${HOTFIX_GREEN_SHA:-}" = "$sha" ] || skip "hotfix waits for CI and the emulator (job hotfix in ci.yml)"
elif [ "${CI_GREEN_SHA:-}" != "$sha" ]; then
    runs=$(gh run list --workflow ci.yml --commit "$sha" --limit 20 --json status,conclusion)
    jq -e 'any(.[]; .conclusion == "success")' <<<"$runs" >/dev/null ||
        skip "CI on ${sha:0:7}: $(jq -r '.[0] // {} | "\(.status // "no run") \(.conclusion // "")"' <<<"$runs")"
fi

# GitHub computes mergeability lazily: UNKNOWN right after a push.
for _ in 1 2 3 4 5 6; do
    mergeable=$(gh pr view "$num" --json mergeable -q .mergeable)
    [ "$mergeable" != UNKNOWN ] && break
    sleep 5
done
if [ "$mergeable" = CONFLICTING ]; then
    marker='<!-- automerge -->'
    gh pr view "$num" --json comments -q '.comments[].body' | grep -qF "$marker" ||
        gh pr comment "$num" --body "$marker
Конфликт с \`$base\` — автомерж ждёт. Агенту: влить \`origin/$base\`, разрешить, push.

---
_Generated by [Claude Code](https://claude.ai/code)_"
    skip "conflicts with $base"
fi
[ "$mergeable" = MERGEABLE ] || skip "mergeable=$mergeable"

fixes=$(gh pr view "$num" --json closingIssuesReferences \
    -q '.closingIssuesReferences[] | select(.url | contains("/" + env.GH_REPO + "/issues/")) | .number')
gh pr merge "$num" --merge --delete-branch --match-head-commit "$sha"
echo "PR #$num merged into $base"
gh workflow run ci.yml --ref "$base" # main: builds and publishes the update
done_text="Сделано в #$num (влит в \`dev\`)."
[ "$base" = main ] && done_text="Исправлено хотфиксом #$num: сборка выпускается на телефоны."

for n in $fixes; do
    issue=$(gh issue view "$n" --json state,labels)
    if [ "$(jq -r .state <<<"$issue")" = OPEN ]; then
        gh issue close "$n" --reason completed --comment "$done_text

---
_Generated by [Claude Code](https://claude.ai/code)_"
    fi
    old=$(jq -r '[.labels[].name | select(startswith("status:"))] | join(",")' <<<"$issue")
    [ -z "$old" ] || gh issue edit "$n" --remove-label "$old"
    echo "Issue #$n closed"
done
[ -z "$fixes" ] || gh workflow run tasks.yml --ref dev
if [ "$base" = main ]; then
    bash "${BACKMERGE:-$(dirname "$0")/backmerge.sh}" "$num" || echo "::warning::main was not merged into dev — see the PR comment"
fi
